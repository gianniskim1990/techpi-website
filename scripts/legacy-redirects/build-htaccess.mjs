// Writes the redirect block for the legacy WordPress site pigiota314.gr (docs/launch/PIGIOTA314_GR_REDIRECT.md).
//
//   node scripts/legacy-redirects/build-htaccess.mjs
//
// Reads pigiota314-gr.tsv (path, status, target; taken from the owner-approved REDIRECT_MAPPING.md) and writes
// pigiota314-gr.htaccess, to be pasted at the very top of the site's .htaccess, above "# BEGIN WordPress".
//
// - Only the hosts pigiota314.gr and www.pigiota314.gr: subdomains on the same server (demo., hair.) are untouched.
// - Each mapped path, with or without its trailing slash and in any ASCII case, answers one 301 straight to its final
//   techpi.eu URL, with the query string dropped; retired demo and archive pages answer 410.
// - Everything else on the two hosts answers 410, except what the old WordPress and the server still need, so the
//   owner can still sign in and back it up: /wp-content/, /wp-admin/, /wp-includes/, wp-login.php, wp-cron.php, wp-json,
//   the old sitemaps (they list the old URLs, so crawlers find the redirects sooner), /.well-known/ (certificates).
//   robots.txt answers 410 on purpose: for crawlers a 4xx means "no restrictions", while the old WordPress sometimes
//   answers it with a 500, which stops crawling (and so stops search engines from seeing the redirects).
// No dependencies. Exits 1 if the data file is invalid.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const HOST = '^(www\\.)?pigiota314\\.gr(:[0-9]+)?$';
const KEEP = [
  '^/(wp-admin|wp-includes|wp-content|wp-json|\\.well-known)(/|$)',
  '^/(wp-login|wp-cron)\\.php$',
  '^/[^/]*sitemap[^/]*\\.(xml|xsl)$',
  '^/favicon\\.ico$',
];

export function readMap(file) {
  const rows = fs.readFileSync(file, 'utf8').split(/\r?\n/).filter(Boolean).map((line) => {
    const [from, status, to = ''] = line.split('\t');
    if (!from.startsWith('/')) throw new Error(`Path must start with "/": ${line}`);
    if (status === '301' && !/^https:\/\/techpi\.eu\/[^\s?#]*$/.test(to)) throw new Error(`Bad target: ${line}`);
    if (status === '410' && to) throw new Error(`A 410 has no target: ${line}`);
    if (status !== '301' && status !== '410') throw new Error(`Status must be 301 or 410: ${line}`);
    return { from, status, to };
  });
  const seen = new Set();
  for (const r of rows) {
    const key = pathKey(r.from);
    if (seen.has(key)) throw new Error(`Duplicate path (ignoring case and trailing slash): ${r.from}`);
    seen.add(key);
  }
  return rows;
}

/** How Apache will compare a path with the rules below: lower-case ASCII, no trailing slash. */
export const pathKey = (p) => p.replace(/\/+$/, '').replace(/[A-Z]/g, (c) => c.toLowerCase());

const escape = (s) => s.replace(/[.+*?()[\]{}|^$\\]/g, '\\$&');

/** RewriteRule pattern for a path, matched (per directory) without its leading slash. */
export const pattern = (p) => {
  const bare = p.replace(/^\/+/, '').replace(/\/+$/, '');
  return bare ? `^${escape(bare)}/?$` : '^$';
};

export function build(rows) {
  const cond = `RewriteCond %{HTTP_HOST} ${HOST} [NC]`;
  const out = [
    '# BEGIN pigiota314.gr -> techpi.eu',
    '# Generated by scripts/legacy-redirects/build-htaccess.mjs in the TechPi repository; do not edit by hand.',
    '# Keep this block above "# BEGIN WordPress". To undo the redirect, delete the block.',
    // A plain message: otherwise the server hands the 410 to WordPress, which answers it with its own 404 or 301.
    'ErrorDocument 410 "Gone. pigiota314 is now TechPi: https://techpi.eu/el/"',
    '<IfModule mod_rewrite.c>',
    'RewriteEngine On',
    '',
  ];
  for (const r of rows) {
    // Only the original request: not WordPress's own internal rewrite to index.php.
    out.push(cond, 'RewriteCond %{ENV:REDIRECT_STATUS} ^$');
    // A trailing "?" drops the query string (works on every Apache 2.x, unlike the QSD flag).
    out.push(r.status === '301' ? `RewriteRule ${pattern(r.from)} ${r.to}? [R=301,NC,L]` : `RewriteRule ${pattern(r.from)} - [G,NC]`);
  }
  out.push('', '# Everything else on pigiota314.gr is gone, except what the old WordPress and the server still use.');
  out.push(cond, 'RewriteCond %{ENV:REDIRECT_STATUS} ^$');
  for (const k of KEEP) out.push(`RewriteCond %{REQUEST_URI} !${k} [NC]`);
  out.push('RewriteRule ^ - [G]', '</IfModule>', '# END pigiota314.gr -> techpi.eu', '');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows = readMap(path.join(here, 'pigiota314-gr.tsv'));
  fs.writeFileSync(path.join(here, 'pigiota314-gr.htaccess'), build(rows));
  const n = (s) => rows.filter((r) => r.status === s).length;
  console.log(`pigiota314-gr.htaccess: ${n('301')} redirects (301), ${n('410')} retired (410), all other paths 410.`);
}
